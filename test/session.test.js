'use strict';
const {test}=require('node:test'), assert=require('node:assert/strict');
const {spawn}=require('node:child_process'), fs=require('node:fs'), os=require('node:os'), path=require('node:path');
test('current chat review lifecycle, isolation, queue recovery and approval', async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'docreview-test-'));
 const port=24517, root=path.resolve(__dirname,'..');
 const env={...process.env,DOCREVIEW_PORT:String(port),DOCREVIEW_DATA:dir,DOCREVIEW_AUTODISPATCH:'0'};
 let daemon;
 const start=async()=>{
  daemon=spawn(process.execPath,[path.join(root,'server/daemon.js')],{env,stdio:'ignore',windowsHide:true});
  for(let i=0;i<60;i++){try{await fetch('http://127.0.0.1:'+port+'/api/ping');return;}catch{await new Promise(r=>setTimeout(r,50));}}
  throw Error('daemon failed to start');
 };
 const stop=async()=>{const exited=new Promise(r=>daemon.once('exit',r));daemon.kill();await exited;};
 const api=async(p,b)=>{const r=await fetch('http://127.0.0.1:'+port+p,b?{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(b)}:{});const j=await r.json();if(!r.ok)throw Error(j.error);return j;};
 const tool=(name,args={},sid='chat-A')=>new Promise((resolve,reject)=>{
  const c=spawn(process.execPath,[path.join(root,'server/client.js'),name,JSON.stringify(args)],{env:{...env,CODEX_THREAD_ID:sid},windowsHide:true});
  let out='',err='';c.stdout.on('data',d=>out+=d);c.stderr.on('data',d=>err+=d);
  c.on('exit',code=>{try{const r=JSON.parse(out);if(code)reject(Error(r.content?.[0]?.text||err));else resolve(r.content[0].text);}catch(e){reject(Error(out+err+e));}});
 });
 try{
  await start();
  assert.equal(JSON.parse(await tool('doc_review_start')).session_id,'chat-A');
  await assert.rejects(tool('doc_review_start',{},'chat-B'),/另一条聊天/);
  await api('/api/open',{name:'sample.txt',b64:Buffer.from('Original paragraph.').toString('base64')});
  await assert.rejects(tool('doc_read',{},'chat-B'),/发起审阅/);
  const b=(await api('/api/state')).blocks[0];
  const c=await api('/api/comments',{blockId:b.id,quote:'Original',text:'Change Original to Revised',send:true});
  const task=JSON.parse(await tool('doc_review_next'));
  assert.match(task.prompt,/Change Original to Revised/);
  assert.equal((await api('/api/state')).agent.threadId,'chat-A');
  assert.equal(JSON.parse(await tool('doc_review_next')).resumed,true);
  await assert.rejects(api('/api/open',{name:'other.txt',b64:''}),/先完成/);
  await assert.rejects(tool('doc_review_finish',{task_id:task.task_id}),/comment_reply/);
  await tool('doc_edit_block',{block_id:b.id,text:'Revised paragraph.'});
  await tool('comment_reply',{comment_id:c.id,text:'Changed Original to Revised.'});
  await tool('doc_review_finish',{task_id:task.task_id,text:'Done'});
  await api('/api/comment/followup',{id:c.id,text:'Please explain this change.'});
  const follow=JSON.parse(await tool('doc_review_next'));
  assert.match(follow.prompt,/Please explain this change/);
  assert.match(follow.prompt,/Changed Original to Revised/);
  await assert.rejects(tool('doc_review_finish',{task_id:follow.task_id}),/comment_reply/);
  await assert.rejects(api('/api/comment/followup',{id:c.id,text:'Duplicate'}),/正在处理中/);
  await tool('comment_reply',{comment_id:c.id,text:'The wording follows your request.'});
  await tool('doc_review_finish',{task_id:follow.task_id,text:'Explained'});
  assert.equal((await api('/api/state')).blocks[0].state,'changed');
  await tool('doc_review_decide',{decision:'reject',block_id:b.id});
  assert.equal((await api('/api/state')).blocks[0].text,'Original paragraph.');
  await tool('doc_edit_block',{block_id:b.id,text:'Approved paragraph.'});
  await tool('doc_review_decide',{decision:'accept'});
  assert.equal((await api('/api/state')).blocks[0].state,'same');
  await tool('doc_set_fonts',{latin:'Arial',east_asia:'华文中宋'});
  const out=path.join(dir,'result.docx');await tool('doc_export',{path:out});
  assert.equal(fs.readFileSync(out).subarray(0,2).toString(),'PK');
  const xml=require('../server/zip').unzip(fs.readFileSync(out)).find(f=>f.name==='word/document.xml').data.toString('utf8');
  assert.match(xml,/w:ascii="Arial"/);assert.match(xml,/w:eastAsia="华文中宋"/);
  const whole=await api('/api/chat',{text:'Summarize this document'});
  assert.equal(whole.blockId,'__document__');
  const next=JSON.parse(await tool('doc_review_next'));
  await new Promise(r=>setTimeout(r,300));await stop();await start();
  assert.equal((await api('/api/state')).agent.threadId,'chat-A');
  assert.equal(JSON.parse(await tool('doc_review_next')).task_id,next.task_id);
  await tool('comment_reply',{comment_id:whole.id,text:'Summary'});
  await tool('doc_review_finish',{task_id:next.task_id,text:'Summary'});
  await api('/api/open',{path:out});
  const first=(await api('/api/state')).blocks[0];
  const todo=await api('/api/block/insert',{afterId:first.id,text:'Check references',type:'todo'});
  await api('/api/block/check',{id:todo.id,checked:true});
  await api('/api/block/accept',{id:todo.id});
  const accepted=await api('/api/state');
  assert.equal(accepted.doc.kind,'docx');
  assert.equal(accepted.blocks.find(b=>b.id===todo.id).checked,true);
  assert.equal(accepted.blocks.find(b=>b.id===todo.id).text,'Check references');
  await api('/api/mode',{mode:'view'});
  await assert.rejects(api('/api/block/check',{id:todo.id,checked:false}),/查看模式/);
  await api('/api/mode',{mode:'suggest'});
  await tool('doc_review_release');
  assert.equal(JSON.parse(await tool('doc_review_start',{},'chat-B')).session_id,'chat-B');
 }finally{if(daemon?.exitCode===null)await stop();fs.rmSync(dir,{recursive:true,force:true});}
});
